STYLE_FIELDS = [
    ("off_pass_rate", "pass-play rate", True),
    ("off_ypp", "yards per play", True),
    ("off_yardsPerPassAttempt", "yards per pass att", True),
    ("off_yardsPerRushAttempt", "yards per rush att", True),
    ("off_plays_pg", "plays per game (tempo)", True),
]


def load_team_styles(path=None, season=None):
    path = path or os.path.join(DATA_DIR, "team_stats.csv")
    if not os.path.exists(path):
        return None
    ts = pd.read_csv(path)
    if season is not None and "season" in ts.columns:
        sub = ts[ts["season"] == season]
        if len(sub):
            ts = sub
    else:
        ts = ts[ts["season"] == ts["season"].max()]
    ts["team_id"] = ts["team_id"].astype(str)
    return ts


def _z(series):
    s = pd.to_numeric(series, errors="coerce")
    sd = s.std(ddof=0)
    return (s - s.mean()) / sd if sd and sd > 0 else s * 0.0


def style_report(styles, home_id, away_id, home, away):
    """Quantify how stylistically opposed two teams are, and where the
    sharpest unit mismatches sit.

    Two distinct numbers, deliberately:
      * opposition index -- how DIFFERENT the two teams are (a fast spread
        offense against a slow grinding one). Symmetric, no favorite implied.
      * unit mismatches  -- DIRECTIONAL: this offense's strength against that
        defense's weakness, in standard deviations.

    Neither figure adjusts the spread. Measured effect on out-of-sample
    residuals was statistically indistinguishable from zero.
    """
    if styles is None:
        return None
    s = styles.copy()
    for col in ["off_pass_rate", "off_ypp", "off_yardsPerPassAttempt",
                "off_yardsPerRushAttempt", "off_plays_pg",
                "def_yardsPerPassAttempt", "def_yardsPerRushAttempt", "def_ypp"]:
        if col in s.columns:
            s["z_" + col] = _z(s[col])

    h = s[s["team_id"] == str(home_id)]
    a = s[s["team_id"] == str(away_id)]
    if h.empty or a.empty:
        return None
    h, a = h.iloc[0], a.iloc[0]

    dims = []
    for col, label, _ in STYLE_FIELDS:
        zc = "z_" + col
        if zc in s.columns and pd.notna(h.get(zc)) and pd.notna(a.get(zc)):
            dims.append((label, float(h[zc]), float(a[zc])))

    opposition = float(np.sqrt(np.mean([(hv - av) ** 2 for _, hv, av in dims]))) if dims else None

    mismatches = []
    pairs = [
        ("pass", "z_off_yardsPerPassAttempt", "z_def_yardsPerPassAttempt"),
        ("rush", "z_off_yardsPerRushAttempt", "z_def_yardsPerRushAttempt"),
        ("overall", "z_off_ypp", "z_def_ypp"),
    ]
    for label, ocol, dcol in pairs:
        if ocol in s.columns and dcol in s.columns:
            # def_ z is "yards allowed", so a HIGH z is a WEAK defense
            if pd.notna(h.get(ocol)) and pd.notna(a.get(dcol)):
                mismatches.append({
                    "unit": f"{home} {label} offense vs {away} {label} defense",
                    "edge_sd": round(float(h[ocol] + a[dcol]) / 2.0, 2),
                })
            if pd.notna(a.get(ocol)) and pd.notna(h.get(dcol)):
                mismatches.append({
                    "unit": f"{away} {label} offense vs {home} {label} defense",
                    "edge_sd": round(float(a[ocol] + h[dcol]) / 2.0, 2),
                })
    mismatches.sort(key=lambda m: -abs(m["edge_sd"]))
    return {
        "opposition_index": round(opposition, 2) if opposition is not None else None,
        "dimensions": [{"dimension": d, "home_z": round(hv, 2), "away_z": round(av, 2),
                        "gap_sd": round(hv - av, 2)} for d, hv, av in dims],
        "mismatches": mismatches[:4],
    }


