#!/usr/bin/env python3
"""
Game prediction engine: point spread, total, win probability, and a
style-matchup readout.

WHAT MOVES THE NUMBER, AND WHAT DOES NOT
----------------------------------------
Everything in this file is separated into effects that shift the predicted
MEAN and diagnostics that do not. That split is not stylistic -- it was
measured on this project's own 2023-2025 data (see experiments/):

  MOVES THE MEAN
    * opponent-adjusted OFF/DEF ridge ratings        (the whole model)
    * home field advantage, fitted as a coefficient  (+3.2 to +3.5 pts)
    * starting-QB adjustment, when a change is known (see qb_adjust)

  DOES **NOT** MOVE THE MEAN -- DIAGNOSTIC ONLY
    * pass-offense vs pass-defense "matchup" interaction. Tested directly:
      t = -0.39, R^2 = 0.0001 against out-of-sample residuals. All style
      interaction terms together moved residual std by 0.03 points. It is
      noise. It is displayed because it is genuinely interesting context and
      because it was asked for, but it is NOT allowed to touch the spread.

SIMULATION
----------
Scores are generated by a drive-based multinomial: each possession ends in a
touchdown, a field goal, or nothing. Compared against 2764 real games this
halves key-number error versus drawing from a Normal (real football piles up
on margins of 3 and 7, which continuous noise smears away), while matching
the observed mean and variance. See experiments/sim_distribution_test.py.

Noise is calibrated from OUT-OF-SAMPLE backtest residuals (data/calibration.json).
The in-sample figure understates real game variance by ~15% and would make
every win probability overconfident.
"""

import json
import os

import numpy as np
import pandas as pd

import cfb_ratings as R

from paths import DATA_DIR  # frozen-aware; see paths.py
DEFAULT_SIMS = 20000

# Drive-model parameters, chosen against the empirical score distribution.
MEAN_DRIVES = 12.0
SD_DRIVES = 1.3
FG_RATIO = 0.45          # E[FG drives] / E[TD drives]
PAT_RATE = 0.95
# Expected points of a touchdown drive INCLUDING the extra point. An earlier
# version derived drive probabilities assuming a TD is worth a flat 7.0 while
# the score generator paid 6 + Bernoulli(PAT_RATE) -- expected 6.95 -- which
# left the simulated mean ~0.3 points under the target for high-scoring teams.
TD_PTS = 6.0 + PAT_RATE
FALLBACK_SIGMA = 11.5    # out-of-sample per-team score sigma
# sigma(exp) = a + b*exp, fitted directly on the 1,853 out-of-sample backtest
# residuals (2026-08 refit; binned sd regression gives 8.14 + 0.117*exp).
# Earlier constants (6.56 + 0.097*exp) were ~21% low in absolute level and
# only correct after the blend rescale in simulate(); these are honest on
# their own, and the blend multiplier now sits near 1.0 instead of 1.26.
SIGMA_INTERCEPT = 8.14
SIGMA_SLOPE = 0.117
# Softplus score floor, fitted out-of-sample -- see score_floor()
FLOOR_C = 3.0
FLOOR_S = 4.0

# First-year head coach: measured on the 2024-2025 walk-forward residuals,
# a team with a new head coach underperforms the rating model's expectation
# by ~1.5 points of margin (2024: beta -1.63, t -1.84; 2025: beta -1.43,
# t -1.72; pooled t -2.52 across 693 affected games). It replicated in both
# directions of a fit-one-season/apply-to-the-other holdout (RMSE -0.06 and
# -0.07 on affected games), which is the replication bar every other
# situational factor failed. NOTE: the market prices this fully (incremental
# to the closing line t = -0.66), so it improves PROJECTIONS, not bets.
# Applied margin-only: half to each side, so totals are untouched.
COACH_CHANGE_MARGIN = -1.5


def load_calibration(path=None):
    path = path or os.path.join(DATA_DIR, "calibration.json")
    if not os.path.exists(path):
        return {"score_resid_std": FALLBACK_SIGMA, "resid_corr": 0.0,
                "margin_resid_std": 16.0, "source": "fallback (run backtest.py)"}
    with open(path, encoding="utf-8") as f:
        c = json.load(f)
    oos = c.get("out_of_sample", {})
    # NOTE: this whitelist must carry EVERY key a consumer needs. It silently
    # dropped edge_shrinkage once, which disabled all market calibration in
    # run_report.py -- the factors were fitted and written to disk but never
    # reached the report, so every bet call fell through to the uncalibrated
    # "NO BET" path. It failed safe, but it failed silently. Anything added to
    # calibration.json must be added here too.
    return {
        "score_resid_std": oos.get("score_resid_std", FALLBACK_SIGMA),
        "resid_corr": oos.get("resid_corr", 0.0),
        "margin_resid_std": oos.get("margin_resid_std", 16.0),
        "su_accuracy": oos.get("su_accuracy"),
        "total_calibration": c.get("total_calibration"),
        "edge_shrinkage": c.get("edge_shrinkage"),
        "total_edge_shrinkage": c.get("total_edge_shrinkage"),
        "fcs_augmentation": c.get("fcs_augmentation"),
        "coach_adjustment": c.get("coach_adjustment"),
        "source": "data/calibration.json (walk-forward out-of-sample)",
        # DELIBERATELY NOT FORWARDED: "clv_diagnostic" and "validation_gate".
        # These are monitoring statistics, not calibration. CLV is an upper
        # bound on edge rather than a substitute for it (+0.27 pts measured
        # against the 0.90 pts needed to break even at -110), and the gate is
        # already applied upstream -- evaluate_vs_market.py zeroes
        # shrink_factor itself when the gate fails, so the report reads the
        # gated number and never needs to re-derive it. This is an intentional
        # omission, NOT the silent-drop bug described above.
    }


def calibrate_total(raw_total, calib):
    """Shrink a raw projected total toward the league mean.

    The unshrunk total model is measurably worse than predicting the league
    average (see backtest.fit_total_calibration). Rating errors cancel in a
    margin but accumulate in a total, so totals must be pulled in. This is
    applied to the simulated distribution as a whole -- both the central
    estimate and the interval -- so the reported spread of outcomes shrinks
    with it rather than staying misleadingly wide.
    """
    tc = (calib or {}).get("total_calibration")
    if not tc or tc.get("slope") is None:
        return raw_total, False
    return tc["slope"] * np.asarray(raw_total, dtype=float) + tc["intercept"], True


# ---------------------------------------------------------------------------
# Expected scores
# ---------------------------------------------------------------------------

def score_floor(x, c=FLOOR_C, s=FLOOR_S):
    """Soft floor on a projected score.

    The rating model is linear, so against a badly overmatched opponent it
    happily extrapolates to two or even negative points. Real football does
    not do that: measured out-of-sample, teams projected below 5 points
    actually scored 7.5 on average, and teams projected 5-10 scored 10.3.
    There is a hard floor in the sport -- garbage-time drives, defensive and
    special-teams scores, and opponents emptying the bench all put points on
    the board even in a rout.

    A softplus is the right shape: it converges to the identity for normal
    projections (above ~20 points it is indistinguishable) and bends smoothly
    up toward `c` at the bottom, with no kink to distort the middle.

        f(x) = c + s * log(1 + exp((x - c) / s))

    Fitted on 1,853 out-of-sample games. Applying it improves BOTH margin
    (15.976 -> 15.949 RMSE) and total (16.672 -> 16.609), and removes a
    5.6-point bias in the lowest projection bucket.
    """
    x = np.asarray(x, dtype=float)
    return c + s * np.log1p(np.exp(np.clip((x - c) / s, -50, 50)))


def expected_scores(ratings, home, away, neutral=False, qb_adj=None, floor=True,
                    margin_adj=0.0):
    """Model mean scores. qb_adj maps team -> points added to that team's
    offense (negative for a downgrade at quarterback).

    margin_adj is a HOME-margin adjustment applied half to each side, so it
    moves the margin by exactly margin_adj and the total by zero. Used for
    the first-year-head-coach effect (see coach_margin_adj); anything with a
    measured margin effect but no measured totals effect belongs here rather
    than in qb_adj, which shifts the total too.
    """
    for t in (home, away):
        if not ratings.has(t):
            raise KeyError(f"no rating for {t!r}")
    s = 0.0 if neutral else 1.0
    adj_h = (qb_adj or {}).get(home, 0.0)
    adj_a = (qb_adj or {}).get(away, 0.0)
    eh = ratings.mu + ratings.off[home] - ratings.defn[away] + s * ratings.hfa / 2 + adj_h
    ea = ratings.mu + ratings.off[away] - ratings.defn[home] - s * ratings.hfa / 2 + adj_a
    if margin_adj:
        eh += margin_adj / 2.0
        ea -= margin_adj / 2.0
    if floor:
        return float(score_floor(eh)), float(score_floor(ea))
    return max(eh, 0.5), max(ea, 0.5)


