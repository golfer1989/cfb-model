# Top-level prediction
# ---------------------------------------------------------------------------

def predict_game(ratings, home, away, neutral=False, n_sims=DEFAULT_SIMS,
                 calib=None, styles=None, home_id=None, away_id=None,
                 qb_adj=None, line=None, seed=None, margin_adj=0.0):
    calib = calib or load_calibration()
    eh, ea = expected_scores(ratings, home, away, neutral=neutral, qb_adj=qb_adj,
                             margin_adj=margin_adj)
    sim_h, sim_a = simulate(eh, ea, n_sims=n_sims,
                            sigma=calib["score_resid_std"], seed=seed)
    out = summarize(home, away, sim_h, sim_a, calib=calib)
    out["neutral_site"] = neutral
    out["model_exp_home"] = eh
    out["model_exp_away"] = ea
    out["qb_adj"] = dict(qb_adj or {})
    if line is not None:
        out["cover"] = cover_probability(sim_h, sim_a, line)
        out["line"] = line
    if styles is not None and home_id is not None and away_id is not None:
        out["style"] = style_report(styles, home_id, away_id, home, away)
    return out


def format_game(p, calib=None):
    """Human-readable per-game card."""
    L = []
    site = "neutral site" if p.get("neutral_site") else f"at {p['home']}"
    L.append(f"{p['away']}  at  {p['home']}   ({site})")
    L.append("-" * 66)
    L.append(f"  Projected score : {p['home']} {p['exp_home']:.1f} - "
             f"{p['away']} {p['exp_away']:.1f}")
    L.append(f"  POINT SPREAD    : {p['spread_str']}")
    L.append(f"  PROJECTED TOTAL : {p['total']:.1f}   "
             f"(80% range {p['total_p10']:.0f} - {p['total_p90']:.0f})")
    L.append("")
    L.append(f"  Win probability : {p['home']} {p['home_win_prob']*100:.1f}%  |  "
             f"{p['away']} {p['away_win_prob']*100:.1f}%")
    L.append(f"  Margin (home)   : mean {p['mean_margin']:+.1f}, "
             f"median {p['median_margin']:+.1f}, "
             f"80% range {p['margin_p10']:+.0f} to {p['margin_p90']:+.0f}")
    L.append(f"  Close-game odds : within 3 pts {p['p_within_3']*100:.0f}%, "
             f"within 7 pts {p['p_within_7']*100:.0f}%")
    if "cover" in p:
        c = p["cover"]
        L.append(f"  vs line {p['line']:+g}    : {p['home']} covers "
                 f"{c['home_cover']*100:.1f}%, push {c['push']*100:.1f}%, "
                 f"{p['away']} covers {c['away_cover']*100:.1f}%")
    if p.get("qb_adj"):
        for t, v in p["qb_adj"].items():
            if v:
                L.append(f"  QB adjustment   : {t} {v:+.1f} pts")

    st = p.get("style")
    if st:
        L.append("")
        L.append("  STYLE MATCHUP (diagnostic only -- does NOT move the spread above)")
        if st.get("opposition_index") is not None:
            oi = st["opposition_index"]
            desc = ("very similar styles" if oi < 0.6 else
                    "moderately different" if oi < 1.2 else
                    "stylistic opposites")
            L.append(f"    style opposition index : {oi:.2f} sd  ({desc})")
        for m in st.get("mismatches", [])[:3]:
            L.append(f"    {m['unit']:<52} {m['edge_sd']:+.2f} sd")
    return "\n".join(L)
