def _norm_team(s):
    return (str(s).strip().replace("State", "St").replace("&", "and")
            .replace(".", "").replace("'", "").lower())


def load_coach_changes(seasons, data_dir=None):
    """{season: set of normalized team names with a FIRST-YEAR head coach}.

    A team counts as changed in season S when data/cfbd_coaches_{S}.csv and
    _{S-1}.csv both exist and name different head coaches for it. Coach lists
    for season S are published before season S kicks off, so using them for
    season S games is legitimate preseason information. Missing files degrade
    to an empty set (the adjustment silently no-ops), with a printed note so
    the absence is visible rather than silent.
    """
    import ast
    data_dir = data_dir or DATA_DIR
    by_year = {}
    for yr in sorted({s for s in seasons} | {s - 1 for s in seasons}):
        path = os.path.join(data_dir, f"cfbd_coaches_{yr}.csv")
        if not os.path.exists(path):
            continue
        try:
            c = pd.read_csv(path)
        except Exception:  # noqa: BLE001
            continue
        if "seasons" not in c.columns:
            continue
        m = {}
        for _, r in c.iterrows():
            try:
                yrs = ast.literal_eval(r["seasons"]) if isinstance(r["seasons"], str) else r["seasons"]
            except (ValueError, SyntaxError):
                continue
            for s in (yrs or []):
                if s.get("year") == yr and s.get("school"):
                    m[_norm_team(s["school"])] = f"{r.get('firstName')} {r.get('lastName')}"
        by_year[yr] = m
    out = {}
    for season in seasons:
        cur, prev = by_year.get(season), by_year.get(season - 1)
        if not cur or not prev:
            out[season] = set()
            print(f"  (coach adjustment: no coach data for {season}/{season-1}; "
                  f"skipping -- run fetch_cfbd.py to enable)")
            continue
        out[season] = {k for k, v in cur.items() if k in prev and prev[k] != v}
    return out


def coach_margin_adj(new_coach_set, home, away):
    """Home-margin adjustment for first-year head coaches.

    new_coach_set holds NORMALIZED names (see load_coach_changes). Returns
    COACH_CHANGE_MARGIN * (home_changed - away_changed): a home team with a
    new coach gets -1.5 of margin, an away team with one gives +1.5, both
    cancel. Zero when the set is empty or None.
    """
    if not new_coach_set:
        return 0.0
    h = 1.0 if _norm_team(home) in new_coach_set else 0.0
    a = 1.0 if _norm_team(away) in new_coach_set else 0.0
    return COACH_CHANGE_MARGIN * (h - a)


# ---------------------------------------------------------------------------
# Drive-based Monte Carlo
# ---------------------------------------------------------------------------

def target_sigma(exp_pts, a=SIGMA_INTERCEPT, b=SIGMA_SLOPE):
    """Per-team score sigma as a function of expected points.

    Fitted directly on the 1,853 out-of-sample backtest residuals: sd rises
    from ~8.3 for teams projected around 7 points to ~13.2 around 46. A mild
    slope, NOT proportionality -- a multiplicative noise model would imply a
    ~3.5x spread across that range instead of the observed ~1.6x, and would
    make favorites wildly more volatile than they really are.

    The bare output of this function is meant to be honest on its own (an
    earlier version was ~21% low and only correct after simulate()'s blend
    rescale). simulate() still applies the blend so the LEVEL always tracks
    the current calibration.json even if these constants go stale.
    """
    return np.maximum(a + b * np.asarray(exp_pts, dtype=float), 4.0)


def _drive_variance(exp_pts, mean_drives, sd_drives):
    """Analytic variance of the drive multinomial, so the additive form-noise
    term can be sized to make total variance hit the empirical target."""
    ppd = np.asarray(exp_pts, dtype=float) / mean_drives
    p_td = ppd / (TD_PTS + 3.0 * FG_RATIO)
    p_fg = p_td * FG_RATIO
    per_drive = (TD_PTS ** 2 * p_td * (1 - p_td) + 9.0 * p_fg * (1 - p_fg)
                 - 2 * TD_PTS * 3.0 * p_td * p_fg)
    var_counts = mean_drives * np.maximum(per_drive, 0.0)
    var_pace = (ppd ** 2) * (sd_drives ** 2)   # variance from drive-count spread
    return var_counts + var_pace


def _drive_scores(eff_pts, drives, rng):
    """Simulate one side's score from possession outcomes."""
    n = len(eff_pts)
    eff = np.maximum(eff_pts, 0.5)
    ppd = eff / drives
    p_td = ppd / (TD_PTS + 3.0 * FG_RATIO)
    p_fg = p_td * FG_RATIO
    tot = p_td + p_fg
    scale = np.where(tot > 0.92, 0.92 / np.maximum(tot, 1e-9), 1.0)
    p_td, p_fg = p_td * scale, p_fg * scale

    maxd = int(drives.max())
    u = rng.random((maxd, n))
    live = np.arange(maxd)[:, None] < drives[None, :]
    td = ((u < p_td) & live).sum(axis=0)
    fg = ((u >= p_td) & (u < p_td + p_fg) & live).sum(axis=0)
    pat = rng.random((maxd, n)) < PAT_RATE
    made = ((np.arange(maxd)[:, None] < td[None, :]) & pat).sum(axis=0)
    return 6.0 * td + made + 3.0 * fg


def simulate(exp_h, exp_a, n_sims=DEFAULT_SIMS, sigma=None, seed=None,
             mean_drives=MEAN_DRIVES, sd_drives=SD_DRIVES):
    """Monte Carlo one matchup. Returns simulated (home, away) score arrays.

    Total per-team variance is composed of two parts:
      1. intrinsic possession variance from the drive multinomial, and
      2. additive game-to-game "form" noise (weather, injury, motivation,
         officiating) sized so the total matches the empirically measured
         sigma for a team with that projected score.
    """
    rng = np.random.default_rng(seed)

    drives = np.clip(np.round(rng.normal(mean_drives, sd_drives, n_sims)), 8, 18).astype(int)

    out = []
    for exp in (exp_h, exp_a):
        tgt = float(target_sigma(exp))
        if sigma is not None:
            # blend the global out-of-sample sigma with the score-dependent
            # curve, keeping the curve's shape but honoring the measured level
            tgt = tgt * (sigma / float(target_sigma(26.7)))
        intrinsic = float(_drive_variance(exp, mean_drives, sd_drives))
        s_form = float(np.sqrt(max(tgt ** 2 - intrinsic, 0.0)))
        eff = np.full(n_sims, float(exp)) + rng.normal(0.0, s_form, n_sims)
        out.append(_drive_scores(eff, drives, rng))
    h, a = out

    # college football does not end in a tie -- resolve with an OT coin flip
    tied = h == a
    if tied.any():
        idx = np.flatnonzero(tied)
        home_wins = rng.random(idx.size) < 0.5
        h = h.copy(); a = a.copy()
        h[idx[home_wins]] += 3.0
        a[idx[~home_wins]] += 3.0
    return h, a


def summarize(home, away, sim_h, sim_a, calib=None):
    """Turn a simulated distribution into the numbers a bettor actually wants.

    The MARGIN is used as simulated. The TOTAL is shrunk toward the league
    mean first -- unshrunk totals are measurably worse than guessing the
    average (see calibrate_total).
    """
    margin = sim_h - sim_a
    total_raw = sim_h + sim_a
    total, total_was_calibrated = calibrate_total(total_raw, calib)
    p_home = float((margin > 0).mean() + 0.5 * (margin == 0).mean())

    # Three distinct "spread" numbers -- they are NOT the same thing:
    #   mean   : the model's expected margin (what a projection should quote)
    #   median : the middle outcome, less pulled by blowouts
    #   fair   : the line at which cover probability is 50% (what a book quotes)
    mean_margin = float(margin.mean())
    median_margin = float(np.median(margin))
    fair_line = float(np.percentile(margin, 50))

    return {
        "home": home, "away": away,
        "exp_home": float(sim_h.mean()), "exp_away": float(sim_a.mean()),
        "mean_margin": mean_margin,
        "median_margin": median_margin,
        "fair_spread": fair_line,
        "spread_str": spread_string(home, away, fair_line),
        "home_win_prob": p_home, "away_win_prob": 1.0 - p_home,
        "total": float(np.mean(total)),
        "total_median": float(np.median(total)),
        "total_raw": float(np.mean(total_raw)),
        "total_calibrated": bool(total_was_calibrated),
        "margin_p10": float(np.percentile(margin, 10)),
        "margin_p90": float(np.percentile(margin, 90)),
        "total_p10": float(np.percentile(total, 10)),
        "total_p90": float(np.percentile(total, 90)),
        "p_home_by_3plus": float((margin >= 3).mean()),
        "p_home_by_7plus": float((margin >= 7).mean()),
        "p_within_3": float((np.abs(margin) <= 3).mean()),
        "p_within_7": float((np.abs(margin) <= 7).mean()),
    }


def spread_string(home, away, margin):
    """Book-style line, rounded to the nearest half point."""
    m = round(margin * 2) / 2.0
    if m == 0:
        return f"PK ({home} / {away})"
    if m > 0:
        return f"{home} -{m:g}"
    return f"{away} -{-m:g}"


def cover_probability(sim_h, sim_a, line_home):
    """P(home covers) for a line quoted from the home side, e.g. -7.5."""
    margin = sim_h - sim_a
    adj = margin + line_home
    push = float((adj == 0).mean())
    win = float((adj > 0).mean())
    return {"home_cover": win, "push": push, "away_cover": 1.0 - win - push}


